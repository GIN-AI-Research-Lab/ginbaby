class Growth {
  static const zP3 = -1.8808;
  static const zP15 = -1.0364;
  static const zP85 = 1.0364;
  static const zP97 = 1.8808;

  static _Lms _at(GrowthKind k, Sex s, double month) {
    final m = month.clamp(0.0, 24.0);
    final i = m.floor().clamp(0, 23);
    final f = m - i;
    _Lms get(int idx) {
      switch (k) {
        case GrowthKind.weight:
          return _w[s]![idx];
        case GrowthKind.length:
          final e = _len[s]![idx];
          return _Lms(1, e.$1, e.$2);
        case GrowthKind.head:
          final e = _head[s]![idx];
          return _Lms(1, e.$1, e.$2);
      }
    }

    final a = get(i), b = get(i + 1);
    return _Lms(a.l + (b.l - a.l) * f, a.m + (b.m - a.m) * f, a.s + (b.s - a.s) * f);
  }

  static double zScore(GrowthKind k, Sex s, double month, double x) {
    final p = _at(k, s, month);
    if (p.l.abs() < 1e-6) return math.log(x / p.m) / p.s;
    return (math.pow(x / p.m, p.l) - 1) / (p.l * p.s);
  }

  static double valueAtZ(GrowthKind k, Sex s, double month, double z) {
    final p = _at(k, s, month);
    if (p.l.abs() < 1e-6) return p.m * math.exp(p.s * z);
    return p.m * math.pow(1 + p.l * p.s * z, 1 / p.l).toDouble();
  }

  /// Phân vị (0–100) từ z-score, xấp xỉ chuẩn.
  static double percentile(double z) => 100 * _phi(z);

  static double _phi(double z) {
    // Abramowitz–Stegun 26.2.17
    final t = 1 / (1 + 0.2316419 * z.abs());
    final d = 0.3989423 * math.exp(-z * z / 2);
    final p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))));
    return z > 0 ? 1 - p : p;
  }

  static String name(GrowthKind k) => switch (k) { GrowthKind.weight => 'Cân nặng', GrowthKind.length => 'Chiều dài', GrowthKind.head => 'Vòng đầu' };
  static String unit(GrowthKind k) => k == GrowthKind.weight ? 'kg' : 'cm';

  /// Nhận xét nhẹ nhàng theo z-score.
  static (String, bool) verdict(double z) {
    if (z < -3) return ('Rất thấp so với chuẩn WHO. Nên gặp bác sĩ nhi để được đánh giá.', true);
    if (z < -2) return ('Thấp hơn khoảng thường gặp. Nên hỏi bác sĩ nhi nhất là khi bé chậm tăng hoặc bú kém.', true);
    if (z > 3) return ('Rất cao so với chuẩn WHO. Nên gặp bác sĩ nhi để được đánh giá.', true);
    if (z > 2) return ('Cao hơn khoảng thường gặp. Hãy theo dõi và hỏi bác sĩ nhi ở lần khám tới.', true);
    return ('Nằm trong khoảng thường gặp của chuẩn WHO.', false);
  }
}
